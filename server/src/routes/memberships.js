const express = require('express');
const membershipsController = require('../controllers/memberships');
const auth = require('../middlewares/auth');
const authorize = require('../middlewares/role');
const tenant = require('../middlewares/tenant');
const validate = require('../middlewares/validate');
const asyncHandler = require('../utils/asyncHandler');
const { ROLES } = require('../constants/roles');
const {
  createPlanSchema,
  updatePlanSchema,
  reviewPlanApprovalSchema,
  joinMembershipSchema,
  adminCreateMembershipSchema,
  listMembersSchema,
  verifyMemberSchema,
  requestCancellationSchema,
  reviewCancellationSchema
} = require('../validations/memberships');

const router = express.Router();

router.use(auth, tenant);

// Public within college (Student, Organizer, College Admin)
router.get('/plans', asyncHandler(membershipsController.listPlans));

// College Admin: approve/reject plan generated by organizer
router.patch(
  '/plans/:id/approval',
  authorize(ROLES.COLLEGE_ADMIN),
  validate(reviewPlanApprovalSchema),
  asyncHandler(membershipsController.reviewPlanApproval)
);

// College Admin & Organizer: manage plans
router.post(
  '/plans',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(createPlanSchema),
  asyncHandler(membershipsController.createPlan)
);

router.patch(
  '/plans/:id',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(updatePlanSchema),
  asyncHandler(membershipsController.updatePlan)
);
router.put(
  '/plans/:id',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(updatePlanSchema),
  asyncHandler(membershipsController.updatePlan)
);

// Student: join / my status
router.post(
  '/join',
  authorize(ROLES.STUDENT),
  validate(joinMembershipSchema),
  asyncHandler(membershipsController.join)
);

router.get(
  '/me',
  authorize(ROLES.STUDENT),
  asyncHandler(membershipsController.getMyMembership)
);

// Student: request cancellation within 5 days
router.post(
  '/:id/cancel-request',
  authorize(ROLES.STUDENT),
  validate(requestCancellationSchema),
  asyncHandler(membershipsController.requestCancellation)
);

// College Admin & Organizer: review student cancellation request
router.patch(
  '/:id/review-cancellation',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(reviewCancellationSchema),
  asyncHandler(membershipsController.reviewCancellation)
);

// College Admin & Organizer: list enrolled students for a specific plan
router.get(
  '/plans/:id/members',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  asyncHandler(membershipsController.getPlanMembers)
);

// College Admin & Organizer: list members
router.get(
  '/',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(listMembersSchema, 'query'),
  asyncHandler(membershipsController.listMembers)
);

// College Admin & Organizer: add/grant membership for an organization
router.post(
  '/admin-create',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(adminCreateMembershipSchema),
  asyncHandler(membershipsController.adminCreateMembership)
);

// College Admin & Organizer: delete membership created by any organization
router.delete(
  '/:id',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  asyncHandler(membershipsController.deleteMembership)
);

// College Admin & Organizer: verify member status at gate
router.get(
  '/verify',
  authorize(ROLES.COLLEGE_ADMIN, ROLES.ORGANIZER),
  validate(verifyMemberSchema, 'query'),
  asyncHandler(membershipsController.verifyStatus)
);

module.exports = router;
